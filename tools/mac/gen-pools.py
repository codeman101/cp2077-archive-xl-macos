#!/usr/bin/env python3
"""Generates macos/MacPools.inc: every memory pool the game exports (red::memory::PoolStorageProxy<...>), so the plugin's own memory vault
can serve all of them (ArchiveXL allocates from many pools: Engine, RefCount, Default, Mesh, EntityResource, Jobs2Data, GMPL_Spawn, ...).
Usage: gen-pools.py <game executable> > macos/MacPools.inc
One line per pool: {"<PoolName>", "<mangled template argument>"}. The runtime resolves the five functions with dlsym."""
import re
import subprocess
import sys

binary = sys.argv[1]
out = subprocess.run(["nm", binary], capture_output=True, text=True, check=True).stdout
pat = re.compile(r'^[0-9a-f]+ T __ZN3red6memory16PoolStorageProxyI(.+)E4FreeERNS0_5BlockE$')
rows = {}
for line in out.splitlines():
    m = pat.match(line)
    if not m:
        continue
    t = m.group(1)
    assert t.startswith('N') and t.endswith('E'), t
    b = t[1:-1]
    j = 0
    last = None
    while j < len(b):
        if b[j] == 'S':
            k = b.index('_', j)
            j = k + 1
            continue
        if b[j].isdigit():
            k = j
            while b[k].isdigit():
                k += 1
            n = int(b[j:k])
            last = b[k:k + n]
            j = k + n
            continue
        raise SystemExit("cannot parse " + t)
    if last in rows and rows[last] != t:
        print("// duplicate name %s: %s and %s (first one kept)" % (last, rows[last], t))
        continue
    rows[last] = t

print("// Generated by tools/mac/gen-pools.py from the game executable (Steam 2.3.1). One line per exported memory pool.")
for name in sorted(rows):
    print('{"%s", "%s"},' % (name, rows[name]))
